/**
 * Рядок статусу для інструмента - без «▸» і без трьох крапок: їх додає той,
 * хто показує. Невідомий інструмент - порожньо: краще лишити попередній
 * статус, ніж підписати роботу навмання.
 */
export function toolStatusWord(coreName: string): string {
  const exact = EXACT[coreName];
  if (exact) return exact;
  const hit = BY_PREFIX.find(([p]) => coreName.startsWith(p));
  return hit ? hit[1] : '';
}
