import { describe, it, expect } from 'vitest';
import { mutationErrorText } from '../web/app/src/lib/mutationError.ts';

/* Аудит C2 називає відсутність фідбеку помилок мутацій найбільшою прогалиною
 * фронтенду — і ось чому. Дашборд усюди оновлює екран ОПТИМІСТИЧНО: тап по
 * плитці чек-іну, зміна стадії вакансії, ❤️ — усе миттєво, а запит іде фоном.
 * Коли він падає, react-query акуратно ВІДКОЧУЄ стан, і для власника це
 * виглядає як «тап не зарахувався» без жодної причини. Найімовірніша реакція —
 * тапнути ще раз.
 *
 * Тому в кожному повідомленні перевіряються ДВІ речі: сказано, що зміну НЕ
 * збережено, і сказано, ЩО РОБИТИ. Текст без другого — це просто ввічливе
 * «щось пішло не так». */

const каже = (text: string, re: RegExp) => expect(text).toMatch(re);

describe('mutationErrorText', () => {
  it('офлайн (fetch кидає TypeError) -> звʼязок + «зміну не збережено»', () => {
    const text = mutationErrorText(new TypeError('Failed to fetch'));
    каже(text, /не збережено/i);
    каже(text, /звʼязку|мереж/i);
  });

  it('401/403 -> сесія + що робити (перезапустити з чату)', () => {
    for (const status of [401, 403]) {
      const text = mutationErrorText(new Error(`Подію не збережено (${status})`));
      каже(text, /сесі/i);
      каже(text, /перезапусти/i);
      каже(text, /не збережено/i);
    }
  });

  it('5xx -> сервер + «спробуй ще раз»', () => {
    const text = mutationErrorText(new Error('Налаштування не збережено (502)'));
    каже(text, /сервер/i);
    каже(text, /ще раз/i);
  });

  it('конкретне повідомлення клієнта лишається як є — воно точніше за узагальнення', () => {
    expect(mutationErrorText(new Error('Місто не знайдено'))).toBe('Місто не знайдено');
  });

  it('технічний хвіст «(404)» зрізається — код власнику нічого не додає', () => {
    expect(mutationErrorText(new Error('Не вдалося встановити локацію (404)'))).toBe(
      'Не вдалося встановити локацію',
    );
  });

  it('порожня/невідома помилка все одно каже головне', () => {
    for (const e of [undefined, null, new Error(''), 'дивина']) {
      каже(mutationErrorText(e), /не збережено|дивина/i);
    }
  });
});
