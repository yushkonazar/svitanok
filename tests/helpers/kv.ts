/* In-memory стаб прив'язки BRIEFING (M9).
 *
 * Шістнадцять HTTP-тестів мали дослівно один і той самий обʼєкт із трьох рядків.
 * Копії небезпечні не самі по собі, а тим, що розходяться поступово: одна
 * повертає `undefined` замість `null` на відсутньому ключі, друга забуває
 * `list` — і тест починає доводити не те, що доводив сусідній.
 *
 * ⚠️ `list` за замовчуванням порожній — рівно як у всіх копіях, які цей хелпер
 * замінив. Тести, яким потрібен реальний перелік ключів, передають `listKeys`
 * ЯВНО: мовчазний перехід на «справжній» list змінив би поведінку двадцяти
 * файлів одразу, і це була б уже не заміна копій, а окрема зміна.
 */

export interface MemoryKvOptions {
  /** Імена ключів для `list`. Дефолт — порожній перелік. */
  listKeys?: () => string[];
}

/**
 * Стаб KV поверх переданої мапи. Мапа лишається у викликача — з неї зручно
 * читати й у неї зручно засівати стан ДО запиту.
 */
export function memoryKv(store: Map<string, string>, opts: MemoryKvOptions = {}) {
  return {
    get: async (k: string) => store.get(k) ?? null,
    put: async (k: string, v: string) => void store.set(k, v),
    delete: async (k: string) => void store.delete(k),
    list: async () => ({ keys: (opts.listKeys?.() ?? []).map((name) => ({ name })) }),
  };
}
