/** Блок заповнений, коли відповіли на всі НЕ-soft питання. */
export function isDone(b: Block, answers: Record<string, unknown> | undefined): boolean {
  if (!answers) return false;
  return b.qs.filter((q) => !q.soft).every((q) => answers[q.id] !== undefined);
}
