import type { CheckinSlot } from '../../api/schema.ts';

// Питання чек-іну (фідбек власника, п.7). Дзеркало CHECKIN_FIELDS зі
// stats-core.mjs — значення мусять збігатись, інакше сервер мовчки відкине
// відповідь як невалідну (він ігнорує поле, а не кричить).
//
// Усі відповіді ЗАКРИТІ (число або перелік) свідомо: вільний текст неможливо
// порівняти з учора, а вся цінність чек-іну — у порівнянні.
//
// Найсильніші два питання — `planApply` (скільки подач планую) і `kept` (чи
// зробив): це єдині відповіді, які застосунок може ПЕРЕВІРИТИ проти appliedLog,
// а не лише записати. Решта описує; ці дві — вимірюють.

export interface Question {
  id: string;
  t: string;
  /** [підпис, значення]; значення летить на сервер як є. */
  o: Array<[string, string | number]>;
  /** Необовʼязкове — блок вважається заповненим і без нього. */
  soft?: boolean;
}

export interface Block {
  id: CheckinSlot;
  ic: string;
  nm: string;
  /** Київська година, з якої блок відкритий (кінець = початок наступного). */
  from: number;
  qs: Question[];
}

