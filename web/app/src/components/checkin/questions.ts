/** «1 питання / 2 питання / 5 питань» — слова, правило спільне (lib/plural.ts). */
export function pluralizePytannya(n: number): string {
  return pluralUk(n, ['питання', 'питання', 'питань']);
}

/** Значення мультивибору як масив (сервер так само терпить легасі-рядок). */
export function asList(v: unknown): Array<string | number> {
  if (Array.isArray(v)) return v as Array<string | number>;
  return v === undefined || v === null || v === '' ? [] : [v as string | number];
}

/** Чи головне дня — робота/пошук (керує показом опційних джоб-питань). */
export function isWorkDay(dayAnswers: Record<string, unknown> | undefined): boolean {
  return asList(dayAnswers?.plan).includes('work');
}

/** Чи виконана умова showIf цього питання. */
function condMet(q: Question, answers: Record<string, unknown> | undefined): boolean {
  if (!q.showIf) return true;
  const v = answers?.[q.showIf.q];
  // != null (не !== undefined): explicit-clear лишає null у чернетці як
  // «поки без відповіді» — та сама семантика, що isAnswered нижче.
  return v != null && q.showIf.in.includes(v as string | number);
}

/** Питання блоку, видимі за поточним контекстом (умови + гейт робочого дня). */
export function visibleQuestions(
  b: Block,
  workDay: boolean,
  answers?: Record<string, unknown>,
): Question[] {
  return b.qs.filter((q) => (!q.needsWork || workDay) && condMet(q, answers));
}

/** Питання щоденного ядра — вони й вирішують, чи блок «заповнено». */
export function coreQuestions(
  b: Block,
  workDay: boolean,
  answers?: Record<string, unknown>,
): Question[] {
  return visibleQuestions(b, workDay, answers).filter((q) => !q.deep);
}

/** Питання розділу «Детальніше» — завжди опційні, ніколи не блокують. */
export function deepQuestions(
  b: Block,
  workDay: boolean,
  answers?: Record<string, unknown>,
): Question[] {
  return visibleQuestions(b, workDay, answers).filter((q) => q.deep);
}

/**
 * Чи відповіли на питання (для pad — на обидві осі).
 *
 * != null, не !== undefined: «зняти відповідь» (повторний тап знімає) пише
 * ЯВНИЙ null у чернетку, доки дебаунс не піде на сервер і поле не зникне
 * зовсім — обидва стани мусять читатись як «без відповіді» однаково.
 */
export function isAnswered(q: Question, answers: Record<string, unknown> | undefined): boolean {
  if (!answers) return false;
  if (q.kind === 'pad' && q.pad) {
    return answers[q.pad.x] != null && answers[q.pad.y] != null;
  }
  if (q.kind === 'multi') return asList(answers[q.id]).length > 0;
  return answers[q.id] != null;
}

/**
 * Відповіді, які втратили сенс: питання сховане закритим `showIf`, а значення
 * від попереднього вибору лишилось лежати.
 *
 * ⚠️ НАВІЩО ВЗАГАЛІ ЧИСТИТИ. Сховане питання не перестає існувати для сервера
 * й моделі — воно перестає існувати лише на екрані. Послідовність «ліг пізно →
 * причина: залип у стрічці → передумав, ліг до 23» лишала lateReason у KV, а
 * buildCheckinTops рахує «ночей із пізнім відбоєм» саме за НАЯВНІСТЮ цього
 * поля: блок «чому лягаєш пізно» показував ночі, яких не було. Те саме зі
 * сном: «Спав, 8 годин» → «Не спав» лишало sleepH=8 при sleepKind='none'.
 *
 * Гейт needsWork СВІДОМО не чиститься. Він залежить від ранкового «головне на
 * сьогодні», тобто прибрати «Робота» о 21:00 стерло б уже відповіді вечора —
 * втрата даних у цілком нормальному сценарії. showIf так поводитись не може:
 * його умови локальні (сон → сон, відбій → причина відбою).
 *
 * Цикл до нерухомої точки, а не один прохід: гейти ЛАНЦЮЖКОВІ (sleepKind
 * закриває bedtime, а закритий bedtime закриває lateReason), і за один прохід
 * причина пізнього відбою пережила б зникнення самого відбою.
 */
export function clearGatedAnswers(
  b: Block,
  answers: Record<string, unknown> | undefined,
): Record<string, null> {
  const out: Record<string, null> = {};
  if (!answers) return out;
  const work = { ...answers };
  for (let pass = 0; pass < b.qs.length; pass++) {
    let changed = false;
    for (const q of b.qs) {
      if (!q.showIf || condMet(q, work)) continue;
      const ids = q.kind === 'pad' && q.pad ? [q.pad.x, q.pad.y] : [q.id];
      for (const id of ids) {
        if (work[id] == null) continue;
        work[id] = null;
        out[id] = null;
        changed = true;
      }
    }
    if (!changed) break;
  }
  return out;
}

/** Блок заповнений, коли відповіли на всі НЕ-soft питання ядра. */
export function isDone(b: Block, answers: Record<string, unknown> | undefined): boolean {
  if (!answers) return false;
  const workDay = isWorkDay(answers);
  return coreQuestions(b, workDay, answers)
    .filter((q) => !q.soft && !q.needsWork)
    .every((q) => isAnswered(q, answers));
}
