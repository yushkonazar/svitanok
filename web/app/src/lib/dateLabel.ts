// Компактна дата хедера (дизайн v2): «ЧТ · 16 ЛИП».
// 1:1 з макетом Svitanok.dc.html (dateLabel). Береться поточна дата пристрою —
// це заголовок апки («сьогодні»), а не дата брифінгу.

const WD = ['НД', 'ПН', 'ВТ', 'СР', 'ЧТ', 'ПТ', 'СБ'];
const MN = ['СІЧ', 'ЛЮТ', 'БЕР', 'КВІ', 'ТРА', 'ЧЕР', 'ЛИП', 'СЕР', 'ВЕР', 'ЖОВ', 'ЛИС', 'ГРУ'];

export function dateLabel(d: Date = new Date()): string {
  return `${WD[d.getDay()]} · ${d.getDate()} ${MN[d.getMonth()]}`;
}
