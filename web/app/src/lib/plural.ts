// Українська плюралізація — ОДНЕ правило на весь застосунок (аудит C2/F7).
//
// Доти правило жило в чотирьох копіях (новини, питання, події, листи), і саме
// там, де копію не зробили, вилазила помилка: «5 дні», «5 рази». Це не косметика
// — числа в дашборді читаються як речення, і зламане закінчення підриває довіру
// до самого числа так само, як зайвий нуль.
//
// ⚠️ ЧОМУ mod100 ПЕРЕВІРЯЄТЬСЯ ОКРЕМО. 11-14 — пастка української (і російської,
// і польської) плюралізації: вони закінчуються на 1-4, але вимагають форми
// «багато». Правило «дивись лише на останню цифру» дає «11 день» і «12 дні».

/** Три форми: [1, 2-4, 5+]. Напр. ['день','дні','днів'] -> pluralUk(5,…) = 'днів'. */
export function pluralUk(n: number, forms: [string, string, string]): string {
  const mod10 = Math.abs(n) % 10;
  const mod100 = Math.abs(n) % 100;
  if (mod10 === 1 && mod100 !== 11) return forms[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return forms[1];
  return forms[2];
}
