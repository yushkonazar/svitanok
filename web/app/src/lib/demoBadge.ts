// Чесна позначка «це не твої дані» (аудит C2/F2, B9).
//
// ПРОБЛЕМА, ЯКУ ЦЕ ЗАКРИВАЄ. Клієнт віддає SAMPLE-дані з прапорцем `demo:true`
// у ДВОХ різних випадках: поза Telegram (очікувано — прев'ю) і при відхиленому
// initData ВСЕРЕДИНІ Telegram (401/403: протухла сесія, не той акаунт). Чип у
// шапці читав лише `!inTelegram()`, тож другий випадок виглядав як нормальна
// робота: власник бачив вигадані стріки, воронку й чек-іни як СВОЇ.
//
// Це найгірший клас помилки в застосунку про особисті дані: не «нічого не
// видно», а «видно чуже, схоже на твоє». Тому текст у Telegram інший — прямо
// каже, що дані не його, і натякає на причину (сесія).

export interface DemoBadge {
  /** Короткий підпис у чипі. */
  text: string;
  /** Розгорнуте пояснення (title/aria-label) — чому дані несправжні. */
  hint: string;
}

/**
 * Що показати в чипі: null — усе гаразд, дані справжні.
 *
 * `demo` тут — це АБО-логіка по всіх завантажених джерелах: якщо хоч одне
 * віддало SAMPLE, екран уже змішаний, і мовчати про це не можна.
 */
export function demoBadge(opts: { inTelegram: boolean; demo: boolean }): DemoBadge | null {
  if (!opts.demo) return null;
  return opts.inTelegram
    ? {
        text: 'не твої дані',
        hint: 'Показано демо: Telegram не підтвердив сесію (401/403). Перезапусти застосунок із чату — і побачиш свої дані.',
      }
    : { text: 'демо', hint: 'Демо-дані: застосунок відкрито поза Telegram.' };
}
