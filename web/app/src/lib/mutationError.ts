// Текст тоста про невдалу мутацію (аудит C2: «немає видимого фідбеку помилок
// мутацій»).
//
// ГОЛОВНЕ, ЩО МУСИТЬ СКАЗАТИ ПОВІДОМЛЕННЯ: зміна НЕ збереглась. Дашборд усюди
// оновлює екран оптимістично, а react-query при помилці тихо відкочує стан —
// тобто без тоста тап виглядає як «не зарахувався» без причини, і найімовірніша
// реакція власника: тапнути ще раз (і ще раз).
//
// Друге за важливістю — ЩО РОБИТИ. Тому три випадки розділені: протухла сесія
// (перезапустити з чату), немає зв'язку (спробувати пізніше), збій сервера
// (спробувати ще раз). Решта віддає повідомлення самого клієнта — воно вже
// конкретне («Місто не знайдено») і краще за будь-яке узагальнення.

/** HTTP-статус із повідомлення клієнта: усі вони мають хвіст «(NNN)» і
 *  народжуються в ОДНОМУ файлі (api/client.ts), тож формат стабільний. */
function statusOf(message: string): number | null {
  const m = /\((\d{3})\)\s*$/.exec(message);
  return m ? Number(m[1]) : null;
}

/** Помилка мутації -> рядок для тоста. */
export function mutationErrorText(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error ?? '');

  // fetch кидає TypeError без статусу — це офлайн або обірване зʼєднання.
  // Найчастіший випадок у метро, і саме тут «не зарахувалось» найзагадковіше.
  if (error instanceof TypeError || /failed to fetch|networkerror/i.test(message)) {
    return 'Немає звʼязку — зміну не збережено. Спробуй, коли зʼявиться мережа.';
  }

  const status = statusOf(message);
  if (status === 401 || status === 403) {
    return 'Telegram не підтвердив сесію — зміну не збережено. Перезапусти застосунок із чату.';
  }
  if (status !== null && status >= 500) {
    return 'Сервер не відповів — зміну не збережено. Спробуй ще раз за хвилину.';
  }

  // Повідомлення клієнта вже українською й по суті; показуємо як є, лише без
  // технічного хвоста «(404)» — власнику код нічого не додає.
  const clean = message.replace(/\s*\(\d{3}\)\s*$/, '').trim();
  return clean || 'Зміну не збережено. Спробуй ще раз.';
}
