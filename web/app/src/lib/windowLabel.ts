import { pluralUk } from './plural.ts';

// Підпис глибини блоку статистики.
//
// ⚠️ ПРИВІД. Екран рахував на пʼятьох глибинах одночасно (30/60/90 діб,
// 8 тижнів, «вся історія») і майже ніде цього не писав. Числа стояли поруч,
// тож читались як один період: «найчастіше заважала втома» і «куди йде час» —
// це різні місяці, якщо чек-ін заповнювався нерівно.
//
// ⚠️ І ГІРШЕ: там, де підпис усе-таки був, він показував НЕ ТЕ. Картки
// «ЩО ЗАВАЖАЛО · 12 ДІБ» і «СОЦІАЛЬНИЙ КОНТЕКСТ · 52 ДОБИ» брали поле `days`,
// у якому лежала кількість ЗАПОВНЕНИХ діб, а не глибина вікна. Читалось як
// «за останні 12 днів», означало «12 заповнених із останніх 30».
//
// Тому глибина й наповненість тепер РІЗНІ числа з різними словами, а самі
// значення приходять із сервера (STATS_WINDOWS), не з памʼяті клієнта.

const DAYS: [string, string, string] = ['ДОБУ', 'ДОБИ', 'ДІБ'];
const WEEKS: [string, string, string] = ['ТИЖДЕНЬ', 'ТИЖНІ', 'ТИЖНІВ'];

/**
 * «ЗА 30 ДІБ · 12 ЗАПОВНЕНО» — вікно й скільки в ньому даних.
 *
 * `filled` опційний: там, де блок читає кожну добу вікна (явка по слотах),
 * друге число нічого не додає.
 */
export function daysWindowLabel(days: number, filled?: number): string {
  const head = `ЗА ${days} ${pluralUk(days, DAYS)}`;
  return filled === undefined ? head : `${head} · ${filled} ЗАПОВНЕНО`;
}

/** «ЗА 8 ТИЖНІВ» — для тижневих трендів. */
export function weeksWindowLabel(weeks: number): string {
  return `ЗА ${weeks} ${pluralUk(weeks, WEEKS)}`;
}
