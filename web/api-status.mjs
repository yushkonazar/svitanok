// GET /api/status — ПУБЛІЧНИЙ ендпоінт для зовнішнього бейджа «живий сервіс».
//
// ⚠️ ГОЛОВНИЙ ІНВАРІАНТ: автентифікації немає, тож усе, що звідси виходить,
// виходить ДО ВСІХ. Тіло — рівно одне поле: мітка часу останнього брифінгу.
// Ні ідентифікаторів, ні статистики, ні вмісту самого брифінгу.
//
// ⚠️ ЧОМУ ОКРЕМИЙ KV-КЛЮЧ, а не поле в блобі `state`. У `state` лежать
// нагадування, прогрес роадмепу, ваги mock, стан асистента. Читати його заради
// одного поля означало б тримати весь приватний стан за один баг від публічної
// відповіді — досить не того спреду чи не того ключа. Окремий ключ робить таку
// помилку неможливою за побудовою, а не за уважністю.
//
// Поле береться ЯВНО, а не розгортанням запису: якщо той, хто пише ключ, колись
// почне класти туди більше, публічна відповідь не підхопить це автоматично.

/** Ключ у неймспейсі BRIEFING. Пише оркестратор ПІСЛЯ успішної відправки. */
export const STATUS_KEY = 'publicStatus';

const HEADERS = {
  'content-type': 'application/json; charset=utf-8',
  // Звужений origin, а не '*': ендпоінт мінімальний, але обмеження нічого не
  // коштує. Обробник OPTIONS не потрібен — запит без кастомних заголовків і
  // без credentials, тож preflight не відбувається.
  'access-control-allow-origin': 'https://yushko.dev',
  // Значення змінюється раз на добу, а споживач має 3-секундний таймаут:
  // пʼять хвилин кешу знімають навантаження й не роблять дані застарілими в
  // жодному видимому сенсі.
  'cache-control': 'public, max-age=300',
};

/**
 * Мітка часу останнього брифінгу або null.
 *
 * Усі відхилення (ключа немає, битий JSON, немає поля, нерядкове значення)
 * зводяться до null НАВМИСНО: споживач трактує його як «нічого не показувати»,
 * і це рівно та поведінка, якої треба в кожному з цих випадків. Кидати 500 на
 * биті дані означало б, що бейдж показує «сервіс лежить» тоді, коли лежить
 * лише один KV-запис.
 */
export async function handleStatus(_request, env) {
  let lastBriefingAt = null;
  try {
    const raw = await env.BRIEFING.get(STATUS_KEY);
    const parsed = raw ? JSON.parse(raw) : null;
    const v = parsed?.lastBriefingAt;
    if (typeof v === 'string' && v) lastBriefingAt = v;
  } catch {
    lastBriefingAt = null;
  }
  // 200 з null, а не 404: споживач трактує обидва однаково, але рівний 200
  // лишає його гілку помилки для СПРАВЖНІХ помилок (мережа, таймаут), а не
  // для нормального стану «брифінгу ще не було».
  return new Response(JSON.stringify({ lastBriefingAt }), { status: 200, headers: HEADERS });
}
