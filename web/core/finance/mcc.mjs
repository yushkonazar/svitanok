/** Усі назви груп (22 з `інше`) - для тестів і для підказок власнику. */
export const MCC_CATEGORIES = [...GROUPS.map((g) => g.group), FALLBACK_CATEGORY];

/** @type {Map<number, string>} */
const BY_CODE = new Map();
for (const g of GROUPS) {
  for (const code of g.codes ?? []) {
    // Дубль між групами зробив би категорію залежною від порядку перебору -
    // краще гучно впасти на завантаженні модуля, ніж рахувати «каву» по-різному.
    if (BY_CODE.has(code)) throw new Error(`mcc: код ${code} уже в групі «${BY_CODE.get(code)}»`);
    BY_CODE.set(code, g.group);
  }
}

/**
 * Категорія за MCC. Невідомий або 0 - `інше` (Mono шле 0 на переказах між
 * своїми рахунками).
 * @param {unknown} mcc
 */
export function categoryByMcc(mcc) {
  const n = Number(mcc);
  if (!Number.isInteger(n) || n <= 0) return FALLBACK_CATEGORY;
  const exact = BY_CODE.get(n);
  if (exact) return exact;
  for (const g of GROUPS) {
    for (const [lo, hi] of g.ranges ?? []) {
      if (n >= lo && n <= hi) return g.group;
    }
  }
  return FALLBACK_CATEGORY;
}
