-- Повторювані нагадування (релізний блок PR-7, §3.1): «щопонеділка о 9».
-- Досі нагадування були одноразові - свідоме рішення етапу 3, і найчастіший
-- реальний запит власника впирався у відмову.
--
-- ⚠️ КОЛОНКА ЗАВОЗИТЬСЯ ОКРЕМО ВІД КОДУ, І ЦЕ НАВМИСНО. Workers Builds
-- деплоїть у прод КОЖЕН push (VERIFIED 05.09), а `migrate.yml` застосовує
-- міграції лише на мержі в main. Тобто код, що читає нову колонку, у вікні
-- «push гілки → мерж у main» падав би на живих нагадуваннях. Тому спершу в
-- main їде сама колонка (порожня й нікому не потрібна), і лише наступним
-- релізом - код, який її заповнює й читає.
--
-- Формат `rrule`: підмножина RFC 5545, якої досить для побутових повторів -
-- FREQ=DAILY|WEEKLY|MONTHLY[;BYDAY=MO,TU,...][;INTERVAL=n]. Повний RRULE не
-- потрібен: усе, що складніше, власник однаково скаже словами, і краще чесно
-- відмовити, ніж мовчки зрозуміти інакше.
--
-- NULL = одноразове нагадування, тобто вся чинна поведінка.
ALTER TABLE reminders ADD COLUMN rrule TEXT;

-- Скільки разів повтор уже спрацював - щоб «нагадуй 5 разів» мало де рахуватись
-- і щоб у списку було видно, що це не перше спрацювання.
ALTER TABLE reminders ADD COLUMN recur_count INTEGER NOT NULL DEFAULT 0;
