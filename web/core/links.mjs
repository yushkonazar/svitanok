// Містки між можливостями (релізний блок PR-6, §2 плану).
//
// ЩО ЦЕ. Досі кожна можливість була самодостатньою: подія в календарі нічого
// не знала про маршрут, ідея - про задачі, звіт - про план. Власник щоразу
// мусив сам сказати наступний крок, хоча ядро вже знає, який він. Тут - рівно
// ці містки: одна кнопка після дії, що веде в наступну.
//
// ⚠️ ЧОМУ КНОПКА, А НЕ АВТОМАТ. «Створив подію - поставив нагадування» без
// питання означало б, що система вирішує за власника; а мовчання означає, що
// він мусить памʼятати про звʼязок сам. Кнопка - середина: пропозиція видима,
// ціна тапу нульова, відмова безкоштовна.
//
// Ідентифікатор у callback - id рядка `proposals` («undo:<kind>»), який ядро
// щойно створило: у ньому вже лежить знімок дії, і другого сховища не треба.

/** Префікси кнопок-містків у просторі `m:` (07 §9). */
export const LINK_CB = {
  departure: 'm:dep:',
  ideaTask: 'm:it:',
  report: 'm:wr:',
  bought: 'm:buy:',
};

const ID_RE = /^[A-Za-z0-9-]{1,40}$/;

/**
 * Кнопка-місток під щойно виконаною T0-дією - або порожньо, якщо містка для
 * неї немає. Іде ПЕРЕД «↩»: перше - наступний крок, друге - відмова від того,
 * що вже сталось.
 * @param {string} kind
 * @param {unknown} snapshot - той самий `prev`, що ляже в рядок undo
 * @param {string} undoId
 * @returns {{ text: string, callback_data: string }[][]}
 */
export function followUpButtons(kind, snapshot, undoId) {
  if (!ID_RE.test(undoId)) return [];
  const snap = /** @type {Record<string, unknown>} */ (
    snapshot && typeof snapshot === 'object' ? snapshot : {}
  );
  // 2.1 Подія З МІСЦЕМ: ядро вміє порахувати ETA, тож може сказати, коли
  // виходити. Без місця рахувати нема від чого - кнопки немає.
  if (kind === 'calendar.event' && typeof snap.location === 'string' && snap.location.trim()) {
    return [[{ text: '🚶 Коли виходити', callback_data: `${LINK_CB.departure}${undoId}` }]];
  }
  // 2.3 Ідея - у задачі: тепер є куди (Tasks з етапу 7), і це T0 з «↩».
  if (kind === 'ideas.create') {
    return [[{ text: '📋 У задачі', callback_data: `${LINK_CB.ideaTask}${undoId}` }]];
  }
  return [];
}

/**
 * Кнопки під тижневим звітом (2.5): звіт закінчується блоком «ЩО ЗРОБИТИ», і
 * дві найчастіші дії з нього мають бути на відстані тапу.
 *
 * ⚠️ Без id звіту: обидві дії стосуються ОСТАННЬОГО звіту, а він на момент
 * тапу один. Id тут довелось би дізнатись до відправки, тобто записати звіт
 * ДО того, як власник його побачив, - а порядок навмисно зворотний (доставка
 * важливіша за запис).
 */
export function reportButtons() {
  return [
    [
      { text: '🧭 Перенести незроблене', callback_data: `${LINK_CB.report}carry` },
      { text: '💡 Ідея з висновку', callback_data: `${LINK_CB.report}idea` },
    ],
  ];
}

/**
 * «✅ Купив» під повідомленням про падіння ціни (2.6): закриває бажання й
 * лишає слід у грошах, замість того щоб власник ішов робити це руками.
 * @param {string} wishId
 */
export function boughtButton(wishId) {
  if (!ID_RE.test(wishId)) return [];
  return [{ text: '✅ Купив', callback_data: `${LINK_CB.bought}${wishId}` }];
}

/** Підказки в тред за кнопками-містками - модель дістає їх як текст власника. */
